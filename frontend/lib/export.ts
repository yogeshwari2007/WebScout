import { ResearchResult } from "./types";

/**
 * Helper to escape table cell content for Markdown:
 * - Escapes pipe characters | -> \|
 * - Replaces newlines with a single space
 * - Handles missing or empty values with "Not available"
 */
function formatMarkdownCell(value: unknown): string {
  if (value === null || value === undefined || value === "") {
    return "Not available";
  }
  const str = String(value);
  return str.replace(/\|/g, "\\|").replace(/(\r\n|\n|\r)/g, " ").trim();
}

/**
 * Helper to escape CSV cell value:
 * - Converts value to string
 * - Replaces embedded double quotes with double-quotes ("" -> """")
 * - If string contains comma, double-quote, or newline, wraps in quotes
 */
function formatCsvCell(value: unknown): string {
  if (value === null || value === undefined || value === "") {
    return '""';
  }
  const str = String(value);
  const escaped = str.replace(/"/g, '""');
  if (
    escaped.includes(",") ||
    escaped.includes('"') ||
    escaped.includes("\n") ||
    escaped.includes("\r")
  ) {
    return `"${escaped}"`;
  }
  return escaped;
}

/**
 * Generates clean, well-formatted Markdown from an actual ResearchResult object.
 * Strictly adheres to specifications:
 * - Query title
 * - Executive summary
 * - Comparison criteria
 * - Escaped comparison table
 * - Item breakdown (pros/cons)
 * - Recommendation winner, reasoning & links
 * - Source URLs and statuses
 * - Duration if available
 */
export function exportToMarkdown(result: ResearchResult): string {
  const lines: string[] = [];

  // Title
  lines.push(`# WebScout Research Dossier: ${result.query}`);
  lines.push("");

  // Metadata block
  const dateFormatted = result.createdAt
    ? new Date(result.createdAt).toLocaleString("en-US", {
        dateStyle: "medium",
        timeStyle: "short",
      })
    : new Date().toLocaleString("en-US", {
        dateStyle: "medium",
        timeStyle: "short",
      });

  const durationText = result.durationSeconds
    ? ` • **Duration:** ${result.durationSeconds}s`
    : "";

  lines.push(`**Generated by WebScout Multi-Website Agent** • **Date:** ${dateFormatted}${durationText}`);
  lines.push("");

  // Executive Summary
  lines.push("## Executive Summary");
  lines.push(result.summary ? result.summary.trim() : "No summary available.");
  lines.push("");

  // Comparison Matrix
  lines.push("## Comparative Evaluation Matrix");
  lines.push("");

  const criteriaHeaders = result.criteria || [];
  const tableHeaders = ["Item", ...criteriaHeaders];
  lines.push(`| ${tableHeaders.map(formatMarkdownCell).join(" | ")} |`);
  lines.push(`| ${tableHeaders.map(() => "---").join(" | ")} |`);

  for (const item of result.items) {
    const rowValues = [
      formatMarkdownCell(item.name),
      ...criteriaHeaders.map((criterion) =>
        formatMarkdownCell(item.criteriaValues?.[criterion])
      ),
    ];
    lines.push(`| ${rowValues.join(" | ")} |`);
  }
  lines.push("");

  // Detailed Item Analysis
  lines.push("## Detailed Item Analysis");
  lines.push("");

  for (const item of result.items) {
    lines.push(`### ${item.name}`);
    if (item.url) {
      lines.push(`*Source: [${item.name}](${item.url})*`);
      lines.push("");
    }

    lines.push("**Key Advantages (Pros):**");
    if (item.pros && item.pros.length > 0) {
      for (const pro of item.pros) {
        lines.push(`- ${pro}`);
      }
    } else {
      lines.push("- Not available");
    }
    lines.push("");

    lines.push("**Trade-offs & Considerations (Cons):**");
    if (item.cons && item.cons.length > 0) {
      for (const con of item.cons) {
        lines.push(`- ${con}`);
      }
    } else {
      lines.push("- None reported");
    }
    lines.push("");
  }

  // Key Recommendation
  lines.push("## Synthesis & Final Recommendation");
  lines.push("");
  lines.push(`**Winner:** ${result.recommendation.winner || "Not determined"}`);
  lines.push("");
  lines.push(result.recommendation.reasoning || "No rationale provided.");
  lines.push("");

  if (
    result.recommendation.keyStrengths &&
    result.recommendation.keyStrengths.length > 0
  ) {
    lines.push("**Core Justification Points:**");
    for (const strength of result.recommendation.keyStrengths) {
      lines.push(`- ${strength}`);
    }
    lines.push("");
  }

  if (
    result.recommendation.sourceLinks &&
    result.recommendation.sourceLinks.length > 0
  ) {
    lines.push("**Supporting Citations:**");
    for (const link of result.recommendation.sourceLinks) {
      lines.push(`- [${link.title || link.url}](${link.url})`);
    }
    lines.push("");
  }

  // Sources Consulted
  lines.push("## Target Sources Consulted");
  lines.push("");
  if (result.sources && result.sources.length > 0) {
    for (const src of result.sources) {
      const statusLabel =
        src.status === "success"
          ? "Verified"
          : src.status === "failed"
          ? "Failed"
          : src.status === "timeout"
          ? "Timed Out"
          : "Consulted";
      const title = src.title ? ` - ${src.title}` : "";
      lines.push(`- [${src.hostname}](${src.url}) (${statusLabel})${title}`);
    }
  } else {
    lines.push("- No external sources recorded.");
  }

  return lines.join("\n");
}

/**
 * Copies the Markdown representation to the user's clipboard.
 * Uses modern Clipboard API with robust fallback.
 */
export async function copyMarkdownToClipboard(
  result: ResearchResult
): Promise<boolean> {
  const markdown = exportToMarkdown(result);

  if (
    typeof navigator !== "undefined" &&
    navigator.clipboard &&
    typeof navigator.clipboard.writeText === "function"
  ) {
    try {
      await navigator.clipboard.writeText(markdown);
      return true;
    } catch {
      // Fall through to legacy fallback
    }
  }

  // Fallback for environments where clipboard write is restricted
  if (typeof document !== "undefined") {
    try {
      const textarea = document.createElement("textarea");
      textarea.value = markdown;
      textarea.setAttribute("readonly", "");
      textarea.style.position = "fixed";
      textarea.style.opacity = "0";
      textarea.style.left = "-9999px";
      document.body.appendChild(textarea);
      textarea.select();
      const successful = document.execCommand("copy");
      document.body.removeChild(textarea);
      return successful;
    } catch {
      return false;
    }
  }

  return false;
}

/**
 * Generates and downloads a CSV file of the comparison table.
 * Includes UTF-8 BOM (\uFEFF) for immediate Excel compatibility.
 * Safely triggers download and revokes Object URL.
 */
export function downloadComparisonCsv(
  result: ResearchResult,
  customFilenameQuery?: string
): void {
  const criteria = result.criteria || [];

  // Header row: Item Name, ...dynamic criteria, Key Advantages
  const headers = ["Item Name", ...criteria, "Key Advantages"];
  const csvRows: string[] = [];
  csvRows.push(headers.map(formatCsvCell).join(","));

  // Data rows
  for (const item of result.items) {
    const prosFormatted =
      item.pros && item.pros.length > 0 ? item.pros.join("; ") : "None reported";

    const row = [
      formatCsvCell(item.name),
      ...criteria.map((c) => formatCsvCell(item.criteriaValues?.[c] || "Not available")),
      formatCsvCell(prosFormatted),
    ];
    csvRows.push(row.join(","));
  }

  const csvContent = csvRows.join("\r\n");
  // UTF-8 BOM so Excel opens accented characters and Unicode cleanly
  const BOM = "\uFEFF";
  const blob = new Blob([BOM + csvContent], {
    type: "text/csv;charset=utf-8;",
  });

  // Sanitize filename: webscout-<query>.csv
  const queryPart = (customFilenameQuery || result.query || "research")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .substring(0, 40);

  const filename = `webscout-${queryPart || "comparison"}.csv`;

  if (typeof window !== "undefined") {
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.setAttribute("download", filename);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    setTimeout(() => {
      URL.revokeObjectURL(url);
    }, 1000);
  }
}

from typing import Any, Dict, List
from urllib.parse import urlsplit
from app.models.fetch import FetchResult
from app.services.analyzers.base import BaseAnalyzer


class MockAnalyzer(BaseAnalyzer):
    """
    Mock analyzer providing structured, illustrative research synthesis.
    Clearly marks its output as mock/demo and does not misrepresent fabricated
    conclusions as actual Gemini-generated insights.
    """

    async def analyze(
        self, query: str, contents: List[FetchResult]
    ) -> Dict[str, Any]:
        successful_sources = [c for c in contents if c.is_success]

        # Scenario 1: All sources failed
        if not successful_sources:
            return {
                "summary": (
                    "Unable to generate synthesis: None of the target websites returned accessible content. "
                    "The URLs may have encountered network timeouts, paywalls, or bot protection."
                ),
                "criteria": ["Availability", "Content Accessibility"],
                "items": [],
                "recommendation": {
                    "winner": "No Recommendation Available",
                    "reasoning": "No readable website content could be extracted to evaluate the query.",
                    "source_urls": [c.url for c in contents],
                },
            }

        # Scenario 2: Successful content extracted
        # Build items based on real extracted titles & hosts
        items = []
        criteria = [
            "Source Quality",
            "Content Depth",
            "Key Observation",
            "Reliability",
        ]

        for idx, src in enumerate(successful_sources):
            hostname = urlsplit(src.url).hostname or f"Source {idx + 1}"
            short_host = hostname.replace("www.", "")

            # Sample first 150 chars of real extracted text for proof of extraction
            sample_snippet = (
                src.extracted_text[:140].replace("\n", " ").strip() + "..."
                if src.extracted_text
                else "No text sample"
            )

            items.append({
                "name": src.title if src.title and src.title != "Untitled Document" else f"Option from {short_host}",
                "source_url": src.url,
                "values": {
                    "Source Quality": f"Verified readable DOM ({len(src.extracted_text)} chars extracted)",
                    "Content Depth": "Multi-section technical article",
                    "Key Observation": sample_snippet,
                    "Reliability": "Live external website",
                },
                "pros": [
                    f"Successfully retrieved and parsed from {short_host}",
                    "Semantic content cleaned and formatted without scripts or ads",
                ],
                "cons": [
                    "Analysis produced by Mock Analyzer (Configure Gemini in Step 8 for AI reasoning)",
                ],
            })

        first_winner = items[0]["name"] if items else "Top Candidate"

        return {
            "summary": (
                f"[DEMO / MOCK ANALYSIS] Synthesized overview for query: '{query}'. "
                f"Content was successfully fetched and cleaned from {len(successful_sources)} source(s). "
                f"Note: Detailed AI semantic reasoning will be enabled when Gemini is connected in Step 8."
            ),
            "criteria": criteria,
            "items": items,
            "recommendation": {
                "winner": first_winner,
                "reasoning": (
                    f"Selected '{first_winner}' based on comprehensive information extracted from {successful_sources[0].url}. "
                    f"This is an illustrative verdict generated by the WebScout Mock Analyzer."
                ),
                "source_urls": [s.url for s in successful_sources],
            },
        }
